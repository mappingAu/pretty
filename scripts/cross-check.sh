#!/usr/bin/env bash
# Cross-compilation checks for the Windows, macOS and Android targets.
#
# Compile-only results are labelled as such. Missing std/SDK is SKIPPED, not
# claimed as a port. Logs are kept under build/cross-check/ or
# test-artifacts/cross-check/. The native release builds/tests happen in
# .github/workflows/build.yml, not here.
set -uo pipefail
ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
cd "$ROOT"
export CARGO_TARGET_DIR="$ROOT/target/cross"
CARGO=${CARGO:-$HOME/.cargo/bin/cargo}
RUSTUP=${RUSTUP:-$HOME/.cargo/bin/rustup}
command -v "$CARGO" >/dev/null 2>&1 || CARGO=$(command -v cargo)
command -v "$RUSTUP" >/dev/null 2>&1 || RUSTUP=$(command -v rustup || true)
REPORT="$ROOT/docs/CROSS-COMPILE.md"
LOG_DIR="$ROOT/test-artifacts/cross-check"
mkdir -p "$LOG_DIR"
TABLE=$(mktemp)
DETAILS=$(mktemp)
FEATURE_TABLE=$(mktemp)
trap 'rm -f "$TABLE" "$DETAILS" "$FEATURE_TABLE"' EXIT
: > "$TABLE"; : > "$DETAILS"; : > "$FEATURE_TABLE"

target_row() { printf '| `%s` | %s | %s |\n' "$1" "$2" "$3" >> "$TABLE"; }

check_target() {
  local triple="$1" label="$2" note="$3"
  local log="$LOG_DIR/${triple}.log"
  local installed="false"
  if [ -n "${RUSTUP:-}" ] && "$RUSTUP" target list --installed 2>/dev/null | grep -qx "$triple"; then
    installed="true"
  fi
  if [ "$installed" != true ]; then
    target_row "$triple" "SKIPPED (std missing)" "$note"
    {
      echo "### $triple — $label"
      echo
      echo "**SKIPPED**: Rust std for this target is not installed."
      echo
      echo '```bash'
      echo "rustup target add $triple"
      echo '```'
      echo
    } >> "$DETAILS"
    return
  fi
  echo "=== $triple ==="
  local extra=()
  case "$triple" in
    x86_64-pc-windows-gnu) extra=(--features dx) ;;
    *-apple-darwin) extra=(--features metal) ;;
    aarch64-linux-android) extra=(--features android) ;;
  esac
  "$CARGO" check --target "$triple" -p pretty-app "${extra[@]}" >"$log" 2>&1
  local code=$?
  {
    echo "### $triple — $label"
    echo
    echo '```bash'
    echo "cargo check --target $triple -p pretty-app ${extra[*]}"
    echo '```'
    echo
  } >> "$DETAILS"
  if [ $code -eq 0 ]; then
    target_row "$triple" "COMPILE-ONLY PASS" "$note"
    echo "Result: **cargo check passed**. This is compile-only; no runtime test was performed on this platform." >> "$DETAILS"
  else
    target_row "$triple" "FAIL" "$note"
    {
      echo "Result: **cargo check failed** (exit $code). Representative errors:"
      echo
      echo '```'
      grep -E '^error|error\[' "$log" | head -20 || true
      echo '```'
      echo
      echo "Full log: \`test-artifacts/cross-check/${triple}.log\`"
    } >> "$DETAILS"
  fi
  echo >> "$DETAILS"
}

check_target "x86_64-pc-windows-gnu" "Windows / GNU" "compile-only; dx feature (Direct3D 12) compile-checked"
check_target "x86_64-apple-darwin" "macOS / Intel" "compile-only; metal feature compile-checked"
check_target "aarch64-apple-darwin" "macOS / Apple Silicon" "compile-only; metal feature compile-checked"
check_target "aarch64-linux-android" "Android / arm64" "compile-only; vulkan+gles; APK still needs NDK"

echo "=== host feature combinations ==="
host_feature_check() {
  local name="$1"; shift
  local log="$LOG_DIR/features-${name}.log"
  echo "--- $name: cargo check -p pretty-app $*"
  if "$CARGO" check -p pretty-app "$@" >"$log" 2>&1; then
    printf '| `%s` | PASS |\n' "$name" >> "$FEATURE_TABLE"
  else
    printf '| `%s` | FAIL (test-artifacts/cross-check/features-%s.log) |\n' "$name" "$name" >> "$FEATURE_TABLE"
  fi
}
host_feature_check default
host_feature_check metal --features metal
host_feature_check dx --features dx
host_feature_check vulkan-only --no-default-features --features vulkan
host_feature_check gles-only --no-default-features --features gles

{
  echo "# Cross-compilation and native CI report"
  echo
  echo "Generated: $(date -u '+%Y-%m-%dT%H:%M:%SZ')"
  echo
  echo "Host toolchain: \`$($CARGO --version 2>&1)\`"
  echo
  echo "This report is generated by \`scripts/cross-check.sh\` on a Linux host. It"
  echo "distinguishes **compiled**, **failed** and **skipped** outcomes; compile-only"
  echo "checks do not claim that a platform port is functional. Native Windows/macOS"
  echo "release builds, unit tests and artifacts are produced by"
  echo "\`.github/workflows/build.yml\` and are described at the end of this report."
  echo
  echo "## Target matrix"
  echo
  echo "| Target | Result | Notes |"
  echo "|---|---|---|"
  cat "$TABLE"
  echo
  echo "## Host feature matrix"
  echo
  echo "| Build | Result |"
  echo "|---|---|"
  cat "$FEATURE_TABLE"
  echo
  echo "## Target details"
  echo
  cat "$DETAILS"
  echo "## Backend features and platform support"
  echo
  echo "Vulkan and GLES are the default features. The \`metal\` feature maps to"
  echo "\`wgpu/metal\` and \`dx\` maps to \`wgpu/dx12\`; both are compiled into the"
  echo "native Windows/macOS release binaries by \`.github/workflows/build.yml\`."
  echo "\`auto\` prefers Direct3D 12 on Windows and Metal on macOS, and skips any"
  echo "backend that is not compiled in. A backend that is selected but"
  echo "unavailable fails with a typed error: there is no silent fallback and no"
  echo "CPU rasteriser."
  echo
  echo "## Native CI builds"
  echo
  echo "The Linux host that generates this report has no MinGW or Apple linker, so"
  echo "the cross-target checks above are compile-only. Native release binaries are"
  echo "built and unit-tested by \`.github/workflows/build.yml\`:"
  echo
  echo "| Runner | Backend features | Artifact |"
  echo "|---|---|---|"
  echo "| \`ubuntu-latest\` | default (Vulkan + GLES) | \`pretty-<ver>-linux-x86_64.tar.gz\` |"
  echo "| \`windows-latest\` | \`--features dx\` | \`pretty-<ver>-windows-x86_64.zip\` |"
  echo "| \`macos-latest\` | \`--features metal\` | \`pretty-<ver>-macos-<arch>.app.tar.gz\` and \`.tar.gz\` |"
  echo
  echo "CI also runs \`cargo test --workspace\` on every runner and repeats the"
  echo "renderer backend tests with the native feature (\`--features dx\` on Windows,"
  echo "\`--features metal\` on macOS). It does not launch the GUI and does not create"
  echo "GitHub releases."
  echo
  echo "## Notes"
  echo
  echo "- Compile-only checks do not exercise runtime windowing, packaging or GPU devices."
  echo "- Android requires an NDK plus an \`android-activity\` entry before an APK can be built."
  echo "- Local macOS checks do not prove Metal works at runtime; the native macOS CI job compiles and unit-tests the Metal build but does not run the GUI."
  echo "- Local Windows checks do not prove Direct3D 12 works at runtime; the native Windows CI job compiles and unit-tests the DX12 build but does not run the GUI."
  echo "- Windows GNU checks need a mingw linker only for linking; no Windows runtime test was performed here."
} > "$REPORT"
echo "Cross-compilation report written to $REPORT"
